function formatLuaTable(name, obj) {
    let out = '    ' + name + ' = {\n';
    for (const [k, v] of Object.entries(obj)) {
        const escaped = v.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
        out += '        ' + k + ' = "' + escaped + '",\n';
    }
    out += '    },';
    return out;
}

const targetPath = 'src/WhatsTraining/Localization.lua';
let code = fs.readFileSync(targetPath, 'utf8');

const esESTable = formatLuaTable('esES', esES);
const esMXTable = formatLuaTable('esMX', esMX);

// Pattern to replace existing empty esES and esMX blocks
const pattern = /    esES = \{[\s\S]*?\},\r?\n    esMX = \{[\s\S]*?\},/;
if (!pattern.test(code)) {
    console.error('Could not find esES/esMX block pattern');
    process.exit(1);
}

code = code.replace(pattern, esESTable + '\n' + esMXTable);

fs.writeFileSync(targetPath, code, 'utf8');
console.log('WhatsTraining Localization.lua successfully updated with 185 keys in esES and esMX!');
