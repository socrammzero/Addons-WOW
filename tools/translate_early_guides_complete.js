function translateText(raw) {
    if (!raw) return raw;
    if (EXACT_MAP[raw]) return EXACT_MAP[raw];

    const leadMatch = raw.match(/^(\s*)/);
    const trailMatch = raw.match(/(\s*)$/);
    const lead = leadMatch ? leadMatch[1] : '';
    const trail = trailMatch ? trailMatch[1] : '';
    let core = raw.trim();
    if (!core) return raw;

    if (EXACT_MAP[core]) return lead + EXACT_MAP[core] + trail;
    if (EN_TO_ES[core]) return lead + EN_TO_ES[core] + trail;
    if (EN_TO_ES[core.toLowerCase()]) return lead + EN_TO_ES[core.toLowerCase()] + trail;

    for (const [pat, rep] of SPANGLISH_REVERTS) {
        if (pat.test(core)) {
            core = core.replace(pat, rep);
        }
    }

    if (EXACT_MAP[core]) return lead + EXACT_MAP[core] + trail;

    let s = core;
    for (const [pat, rep] of PHRASE_RULES) {
        s = s.replace(pat, rep);
    }

    // Replace multi-word / capitalized official WoW entities inside the sentence
    s = s.replace(/\b[A-Z][a-zA-Z'-]+(?:\s+(?:of|the|for|in|on|to|and|[A-Z][a-zA-Z'-]+)){1,5}\b/g, (m) => {
        return EN_TO_ES[m] || EN_TO_ES[m.toLowerCase()] || m;
    });

    for (const [pat, rep] of CLAUSE_AND_WORD_RULES) {
        s = s.replace(pat, rep);
    }

    // Cleanup Spanish contractions & extra spaces
    s = s.replace(/\bde el\b/g, 'del').replace(/\ba el\b/g, 'al').replace(/\s{2,}/g, ' ').trim();

    return lead + s + trail;
}

