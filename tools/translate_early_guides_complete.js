const DIRECTIVE_STRINGS = new Set(['multitext', 'GUIDE', 'prereqs']);
let totalFilesUpdated = 0;
let totalStringsUpdated = 0;

for (let i = 1; i <= 21; i++) {
    const num = String(i).padStart(4, '0');
    const file = `src/Journey/BundledContent/Guides/${num}.html`;
    if (!fs.existsSync(file)) continue;

    const html = fs.readFileSync(file, 'utf8');
    const m = html.match(/^([\s\S]*?<p>\r?\n)([\s\S]*?)(\r?\n\s*<\/p>[\s\S]*)$/);
    if (!m) continue;

    const header = m[1];
    const b64 = m[2].replace(/\s+/g, '');
    const footer = m[3];
    const lua = Buffer.from(b64, 'base64').toString('utf8');

    let changedInFile = 0;

    // 1. Key = "value" pairs
    let updatedLua = lua.replace(/\b([a-zA-Z_]\w*)\s*=\s*"((?:[^"\\]|\\.)*)"/g, (full, key, rawVal) => {
        if (IGNORE_KEYS.has(key)) return full;
        const unescaped = rawVal.replace(/\\"/g, '"');
        const tr = translateText(unescaped);
        if (tr !== unescaped) {
            changedInFile++;
            totalStringsUpdated++;
            return `${key} = "${tr.replace(/"/g, '\\"')}"`;
        }
        return full;
    });

    // 2. Positional strings: preceded by { or , and optional whitespace, not followed by =
    updatedLua = updatedLua.replace(/([\{,]\s*)"((?:[^"\\]|\\.)*)"(\s*(?![=\w]))/g, (full, prefix, rawVal, suffix) => {
        if (DIRECTIVE_STRINGS.has(rawVal) || rawVal.includes('|')) return full;
        const unescaped = rawVal.replace(/\\"/g, '"');
        const tr = translateText(unescaped);
        if (tr !== unescaped) {
            changedInFile++;
            totalStringsUpdated++;
            return `${prefix}"${tr.replace(/"/g, '\\"')}"${suffix}`;
        }
        return full;
    });

    if (changedInFile > 0) {
        const newB64Raw = Buffer.from(updatedLua, 'utf8').toString('base64');
        const lines = [];
        for (let pos = 0; pos < newB64Raw.length; pos += 76) {
            lines.push(newB64Raw.slice(pos, pos + 76));
        }
        const newHtml = header + lines.join('\r\n') + footer;
        fs.writeFileSync(file, newHtml, 'utf8');
        totalFilesUpdated++;
    }
}

